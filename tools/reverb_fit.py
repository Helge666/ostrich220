"""
Fit U220Reverb's tuning to a hardware recording of make_reverb_probe.py, automatically:
render the reverb alone for the current tuning (u220_reverb_run, seconds), measure it
against the hardware band by band and window by window (reverb_edr.Probe), correct, and
again -- no human in the loop, no rebuild.

    tools/reverb_fit.py HW.wav EMU_DRY.wav SEND LIST.txt --run u220_reverb_run
        [--start plugin/core/u220_reverb_tuning.inc] [--iterations 8]
        [--out-inc plugin/core/u220_reverb_tuning.inc] [--out-txt tuning.txt]

EMU_DRY.wav and SEND come from one `u220_render --out EMU_DRY.wav --send-out SEND` run
of the same times file (SEND.rev.f32, .cho.f32 and .params.txt are what is replayed).

What is fitted, per type and Time point (the probe's "level 31" slots at Time 0, 8, 16,
24, 31 are exactly the tuning's points):

  output EQ  each octave band moves by the band's level error -- Ostrich minus hardware,
             energy over the trusted windows, so the early, loud part of the tail counts
             most
  decay      Room1..Hall2 only: the low (125-250 Hz), mid (500 Hz-1 kHz) and high
             (4-8 kHz) decay rate moves by the slope of the level error over the
             windows from 50 ms on (a straight line through error vs time: if Ostrich
             falls behind the hardware later on, its decay is too fast).  Not a T20
             ratio: the hardware's rooms flatten out late, which T20 does not see
  gate       the Gate's hold and release, from the broadband envelope: the release slope
             (between 10 and 30 dB under the open level) scales by hardware / Ostrich,
             the hold moves by the difference in when each falls 10 dB
  feedback   Delay, CrossDelay: the gain per repeat at FB 0, 15 and 31, from the same
             error slope (the probe's Time slots run at FB 15, two more at 0 and 31)

All damped, so the coupled bands (neighbouring EQ peaks overlap, and a decay change
moves the level too) settle over the iterations.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

import numpy as np
from scipy.signal import lfilter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reverb_edr import BANDS, SR, WINDOWS, Probe  # noqa: E402

TYPES = ['Room1', 'Room2', 'Room3', 'Hall1', 'Hall2', 'Gate', 'Delay', 'CrossDelay']
TIME_AT = [0, 8, 16, 24, 31]
DECAY_GROUPS = [(0, 1), (2, 3), (5, 6)]       # BANDS indices for low / mid / high
EQ_STEP, RT_STEP = 0.8, 0.7
SHELF_HZ, SHELF_DB, SHELF_Q = 5200.0, -3.3, 0.5    # the core's output stage


class Tuning:
    def __init__(self, text):
        self.gain, self.size, self.pre = {}, {}, {}
        self.gate = np.zeros((5, 2))                # hold ms, release dB/s
        self.fbcurve = {6: [0.0, 0.25, 0.745], 7: [0.191, 0.25, 0.48]}
        self.rt = np.zeros((6, 5, 3))
        self.eq = np.zeros((8, 5, 7))
        for line in text.splitlines():
            line = line.split('#')[0].split()
            if not line:
                continue
            k, t = line[0], int(line[1])
            v = [float(x) for x in line[2:]]
            if k == 'gain':
                self.gain[t] = v[0]
            elif k == 'size':
                self.size[t] = v[0]
            elif k == 'pre':
                self.pre[t] = v[0]
            elif k == 'rt':
                self.rt[t, int(v[0])] = v[1:]
            elif k == 'eq':
                self.eq[t, int(v[0])] = v[1:]
            elif k == 'gate':
                self.gate[int(v[0])] = v[1:]
            elif k == 'fbcurve':
                self.fbcurve[t] = v[:3]

    def text(self):
        out = []
        for t in range(8):
            out.append(f'gain {t} {self.gain[t]:.4f}')
            if t >= 6:
                out.append(f'fbcurve {t} ' + ' '.join(f'{v:.4f}' for v in self.fbcurve[t]))
            if t < 6:
                out.append(f'size {t} {self.size[t]:.3f}')
                out.append(f'pre {t} {self.pre[t]:.1f}')
                for i in range(5):
                    out.append(f'rt {t} {i} ' + ' '.join(f'{v:.3f}' for v in self.rt[t, i]))
            if t == 5:
                for i in range(5):
                    out.append(f'gate 5 {i} {self.gate[i, 0]:.1f} {self.gate[i, 1]:.1f}')
            for i in range(5):
                out.append(f'eq {t} {i} ' + ' '.join(f'{v:.2f}' for v in self.eq[t, i]))
        return '\n'.join(out) + '\n'


def read_tuning(path):
    s = open(path).read()
    m = re.search(r'R"TUNING\((.*)\)TUNING"', s, re.S)
    return Tuning(m.group(1) if m else s)


def write_inc(path, tuning, note):
    head = ['# U220Reverb tuning: generated by tools/reverb_fit.py, read by ReverbTuning::parse.',
            '# Types 0..7 = Room1 Room2 Room3 Hall1 Hall2 Gate Delay CrossDelay; time index 0..4 =',
            '# Time 0 8 16 24 31.  rt T I = decay (s) low/mid/high; eq T I = dB at 125 Hz .. 8 kHz.']
    head += ['# ' + l for l in note.splitlines()]
    with open(path, 'w', newline='\n') as f:
        f.write('R"TUNING(\n' + '\n'.join(head) + '\n' + tuning.text() + ')TUNING"\n')


def shelf_coeffs():
    A = 10 ** (SHELF_DB / 40)
    w = 2 * np.pi * SHELF_HZ / SR
    c, al = np.cos(w), np.sin(w) / (2 * SHELF_Q)
    sa = 2 * np.sqrt(A) * al
    a0 = (A + 1) - (A - 1) * c + sa
    b = [A * ((A + 1) + (A - 1) * c + sa), -2 * A * ((A - 1) + (A + 1) * c), A * ((A + 1) + (A - 1) * c - sa)]
    a = [a0, 2 * ((A - 1) - (A + 1) * c), (A + 1) - (A - 1) * c - sa]
    return np.array(b) / a0, np.array(a) / a0


def render(run, send, tuning, work):
    tf = os.path.join(work, 'tuning.txt')
    of = os.path.join(work, 'out.f32')
    open(tf, 'w').write(tuning.text())
    subprocess.run([run, send, '--tuning', tf, '--out', of], check=True, stdout=subprocess.DEVNULL)
    x = np.fromfile(of, dtype=np.float32).astype(np.float64).reshape(-1, 2)
    b, a = shelf_coeffs()
    return lfilter(b, a, x, axis=0)


FB_AT = [0, 15, 31]


def fit_slots(probe):
    """(slot, type, time index, FB index): the Time slots (FB 15) and the delays' FB ones."""
    out = []
    for s in probe.slots:
        m = re.match(r'(\w+) time (\d+) level 31$', s['label'])
        if m and m.group(1) in TYPES and int(m.group(2)) in TIME_AT:
            out.append((s, TYPES.index(m.group(1)), TIME_AT.index(int(m.group(2))), 1))
        m = re.match(r'(Delay|CrossDelay) time (\d+) fb (\d+)$', s['label'])
        if m and int(m.group(2)) in TIME_AT and int(m.group(3)) in FB_AT:
            out.append((s, TYPES.index(m.group(1)), TIME_AT.index(int(m.group(2))),
                        FB_AT.index(int(m.group(3)))))
    return out


def gate_shape(env):
    """(time it falls 10 dB under the open level, release slope dB/s) of a broadband
    energy envelope; the open level is the peak of 20 ms frames 80-300 ms after the
    hit (the dry drums are 30 dB or more under the gate there)."""
    from reverb_edr import PRE
    f = int(0.02 * SR)
    e = env.sum(0)
    n = len(e) // f
    db = 10 * np.log10(e[:n * f].reshape(n, f).mean(1) + 1e-20)
    t = (np.arange(n) + 0.5) * 0.02 - PRE
    top = db[(t > 0.08) & (t < 0.3)].max()
    after = np.nonzero((t > 0.08) & (db < top - 10))[0]
    if not len(after):
        return np.nan, np.nan
    t10 = t[after[0]]
    sel = (t >= t10) & (db < top - 10) & (db > top - 30)
    sel &= np.cumsum(~sel & (t > t10)) == 0            # the first stretch only
    if sel.sum() < 3:
        return t10, np.nan
    slope = -np.polyfit(t[sel], db[sel], 1)[0]
    return t10, slope


def measure(probe, slots, rev):
    """Per fit slot: band level errors (dB), RT ratios hw/emu, and the rms error."""
    res = []
    dur = np.array([b - a for a, b in WINDOWS])
    for s, t, i, fbi in slots:
        ec, rt_e = probe.emu_cells(rev, s)
        hc, trust = s['hw_db'], s['trust']
        band = np.full(len(BANDS), np.nan)
        for k in range(len(BANDS)):
            w = trust[k]
            if w.any():
                he = (10 ** (hc[k, w] / 10) * dur[w]).sum()
                ee = (10 ** (ec[k, w] / 10) * dur[w]).sum()
                band[k] = 10 * np.log10(ee / he)
        rt_ratio = np.array([h / e if np.isfinite(h) and np.isfinite(e) and e > 0 else np.nan
                             for h, e in zip(s['rt_hw'], rt_e)])
        cells = np.where(trust, ec - hc, np.nan)
        rms = np.sqrt(np.nanmean(cells ** 2)) if trust.any() else np.nan
        # The error's trend over time, dB/s: a line through the trusted cells from 50 ms
        # on, per decay group, and over all bands from 150 ms on (for the echoes).
        tc = np.array([(a + b) / 2 for a, b in WINDOWS])

        def trend(ks, first):
            x, y = [], []
            for k in ks:
                for j in range(first, len(WINDOWS)):
                    if trust[k, j]:
                        x.append(tc[j])
                        y.append(cells[k, j])
            return np.polyfit(x, y, 1)[0] if len(set(x)) >= 3 else np.nan
        slopes = [trend(g, 1) for g in DECAY_GROUPS]
        r = dict(slot=s, t=t, i=i, fb=fbi, band=band, rt_ratio=rt_ratio, rms=rms, slopes=slopes,
                 slope_all=trend(range(len(BANDS)), 2))
        if t == 5:
            from reverb_edr import band_energy
            r['gate_hw'] = gate_shape(s['hw_env'])
            r['gate_emu'] = gate_shape(band_energy(probe.g * probe._emu_seg(rev, s)))
        res.append(r)
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('hw')
    ap.add_argument('dry')
    ap.add_argument('send')
    ap.add_argument('list')
    ap.add_argument('--run', required=True)
    ap.add_argument('--start', default=os.path.join(os.path.dirname(__file__), '..', 'plugin',
                                                    'core', 'u220_reverb_tuning.inc'))
    ap.add_argument('--iterations', type=int, default=8)
    ap.add_argument('--out-inc')
    ap.add_argument('--out-txt')
    ap.add_argument('--emu-offset', type=float, default=4.0)
    ap.add_argument('--slot', type=float, default=7.0)
    a = ap.parse_args()

    probe = Probe(a.hw, a.dry, a.list, emu_offset=a.emu_offset, slot=a.slot)
    slots = fit_slots(probe)
    print(f'{len(slots)} slots to fit; floor per band (dB): '
          + ' '.join(f'{v:.0f}' for v in probe.floor_db))
    tuning = read_tuning(a.start)
    work = tempfile.mkdtemp(prefix='reverb_fit_')

    history = []
    for it in range(a.iterations + 1):
        rev = render(a.run, a.send, tuning, work)
        res = measure(probe, slots, rev)
        total = np.sqrt(np.nanmean([r['rms'] ** 2 for r in res]))
        history.append(total)
        print(f'\niteration {it}: rms error {total:.2f} dB over all trusted cells')
        for t in range(8):
            rows = [r for r in res if r['t'] == t]
            print(f'  {TYPES[t]:10s} ' + '  '.join(f'T{TIME_AT[r["i"]]}{"" if r["fb"] == 1 else "fb" + str(FB_AT[r["fb"]])}:{r["rms"]:4.1f}' for r in rows))
        if it == a.iterations:
            break
        echo = {}
        for r in res:
            t, i = r['t'], r['i']
            if t >= 6 and np.isfinite(r['slope_all']):
                period = (10 + 12.9 * TIME_AT[i]) / 1000
                g = tuning.fbcurve[t][r['fb']]
                if 0.01 < g < 0.98:
                    d = -20 * np.log10(g) / period + RT_STEP * float(np.clip(r['slope_all'], -30, 30))
                    echo.setdefault((t, r['fb']), []).append(10 ** (-max(d, 0.5) * period / 20))
            if r['fb'] != 1:
                continue                # the FB slots only steer the feedback
            ok = np.isfinite(r['band'])
            tuning.eq[t, i, ok] = np.clip(tuning.eq[t, i, ok] - EQ_STEP * r['band'][ok], -30, 24)
            if t == 5:
                (h10, hs), (e10, es) = r['gate_hw'], r['gate_emu']
                if np.isfinite(h10) and np.isfinite(e10):
                    tuning.gate[i, 0] = float(np.clip(tuning.gate[i, 0] + 0.8 * (h10 - e10) * 1000, 0, 2000))
                if np.isfinite(hs) and np.isfinite(es) and es > 0:
                    tuning.gate[i, 1] = float(np.clip(tuning.gate[i, 1] * (hs / es) ** 0.8, 5, 2000))
            if t <= 4:
                # error slope = hardware decay rate - Ostrich decay rate (dB/s)
                for k, sl in enumerate(r['slopes']):
                    if np.isfinite(sl):
                        d = 60.0 / tuning.rt[t, i, k] + RT_STEP * float(np.clip(sl, -30, 30))
                        tuning.rt[t, i, k] = float(np.clip(60.0 / max(d, 4.0), 0.1, 15.0))
        for (t, f), g in echo.items():
            tuning.fbcurve[t][f] = float(np.clip(np.median(g), 0.0, 0.97))

    print('\nfinal per slot (band level error dB 125..8k | RT hw/emu low mid high):')
    for r in res:
        print(f'  {r["slot"]["label"]:28s} ' + ' '.join('    .' if not np.isfinite(v) else f'{v:+5.1f}' for v in r['band'])
              + ' | ' + ' '.join('  .  ' if not np.isfinite(v) else f'{v:5.2f}'
                                 for v in [np.nanmedian(r['rt_ratio'][list(g)]) if np.isfinite(r['rt_ratio'][list(g)]).any() else np.nan
                                           for g in DECAY_GROUPS]))
    for r in res:
        if r['t'] == 5:
            print(f'  gate T{TIME_AT[r["i"]]}: hw falls 10 dB at {r["gate_hw"][0] * 1000:.0f} ms, '
                  f'{r["gate_hw"][1]:.0f} dB/s; Ostrich {r["gate_emu"][0] * 1000:.0f} ms, {r["gate_emu"][1]:.0f} dB/s')
    note = (f'Fitted to {os.path.basename(a.hw)}: rms error {history[0]:.2f} -> {history[-1]:.2f} dB '
            f'over {len(slots)} slots, {a.iterations} iterations.')
    print('\n' + note)
    if a.out_txt:
        open(a.out_txt, 'w').write(tuning.text())
    if a.out_inc:
        write_inc(a.out_inc, tuning, note)


if __name__ == '__main__':
    main()
